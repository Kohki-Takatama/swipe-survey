import fs from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const source = await fs.readFile('src/model.js', 'utf8');
const backend = await fs.readFile('gas/backend.js', 'utf8');
const generated = await fs.readFile('gas-doPost.gs', 'utf8');
assert.equal(generated, '// Generated by npm run build:gas. Edit src/model.js and gas/backend.js.\n' + source.replace(/^export /gm, '') + '\n' + backend, 'Run npm run build:gas');
const files = (await fs.readdir('src')).filter(f => f.endsWith('.js')).map(f => 'src/' + f);
for (const file of [...files, 'gas/backend.js', 'scripts/build-gas.mjs']) {
  const result = spawnSync(process.execPath, ['--check', file], { stdio: 'inherit' });
  assert.equal(result.status, 0, file);
}
console.log('Syntax and generated GAS verified.');
